package com.coldfriend.world.model;

/** The environmental regions of the wilderness. */
public enum Region {
    /** Dense snowy conifer forest. */
    CONIFER_FOREST,
    /** Open snowy woodland. */
    OPEN_WOODLAND,
    /** Forest on high or steep ground. */
    MOUNTAIN_FOREST,
    /** Low ground along a river. */
    RIVER_VALLEY,
    /** Snow-covered clearing with few trees. */
    CLEARING
}
